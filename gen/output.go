package gen

import (
	"fmt"
	"path"
	"sort"
	"strings"
)

// Output is everything one run produced, with the producer of each file
// remembered so a collision can name both sides.
type Output struct {
	files    map[string][]byte
	producer map[string]string
	order    []string
}

// NewOutput returns an empty Output.
func NewOutput() *Output {
	return &Output{files: map[string][]byte{}, producer: map[string]string{}}
}

// Add records a file.
//
// Two producers claiming one path is an error rather than a last-one-wins,
// because the losing half of a silent overwrite is a file somebody meant to
// ship. protoc-gen-orm-ts derived its output directory from whichever
// generate-marked file happened to be iterated last, so two proto packages in
// one invocation collided with nothing said.
func (o *Output) Add(producer, name string, body []byte) error {
	if err := checkFileName(name); err != nil {
		return fmt.Errorf("%s: %w", producer, err)
	}
	if prev, taken := o.producer[name]; taken {
		return fmt.Errorf("%s and %s both emit %s", prev, producer, name)
	}
	o.producer[name] = producer
	o.files[name] = body
	o.order = append(o.order, name)
	return nil
}

// checkFileName refuses a path that is absolute or escapes the output root.
func checkFileName(name string) error {
	switch {
	case name == "":
		return fmt.Errorf("a file must have a name")
	case path.IsAbs(name), strings.HasPrefix(name, "/"):
		return fmt.Errorf("%q is absolute; buf owns the output root", name)
	}
	for _, seg := range strings.Split(path.Clean(name), "/") {
		if seg == ".." {
			return fmt.Errorf("%q escapes the output root", name)
		}
	}
	return nil
}

// Len is how many files were produced.
func (o *Output) Len() int { return len(o.order) }

// Names is every path, sorted, so a response is stable across runs.
func (o *Output) Names() []string {
	out := append([]string(nil), o.order...)
	sort.Strings(out)
	return out
}

// Body is one file's contents.
func (o *Output) Body(name string) ([]byte, bool) {
	b, ok := o.files[name]
	return b, ok
}

// Producer is who emitted a file.
func (o *Output) Producer(name string) string { return o.producer[name] }

// Manifest is every path this run produced, one per line, sorted.
//
// A protoc plugin can only add files; it is never told the output root and may
// be writing into an archive, so it cannot prune what a previous run left
// behind. Emitting the list is the honest half calque can do: a build can
// remove anything under the root that is not in it, and without that, deleting
// an entity leaves a generated file that compiles forever and that nothing
// regenerates.
func (o *Output) Manifest() []byte {
	var b strings.Builder
	b.WriteString("# Generated by calque. Every file this run produced.\n")
	b.WriteString("# Anything else under the output root is stale.\n")
	for _, name := range o.Names() {
		b.WriteString(name)
		b.WriteByte('\n')
	}
	return []byte(b.String())
}
