// TestReferenceOutput generates from a real proto tree and compares against
// what protoc-gen-orm-ts committed for it.
func TestReferenceOutput(t *testing.T) {
	root := os.Getenv("CALQUE_REFERENCE_PROTO")
	want := os.Getenv("CALQUE_REFERENCE_OUTPUT")
	if root == "" || want == "" {
		t.Skip("set CALQUE_REFERENCE_PROTO and CALQUE_REFERENCE_OUTPUT")
	}

	var files []string
	require.NoError(t, filepath.Walk(root, func(p string, info os.FileInfo, err error) error {
		if err != nil || info.IsDir() || !strings.HasSuffix(p, ".proto") {
			return err
		}
		rel, _ := filepath.Rel(root, p)
		files = append(files, filepath.ToSlash(rel))
		return nil
	}))
	require.NotEmpty(t, files)

	upstream, _ := filepath.Abs("../../testdata/proto/_upstream")
	paths := []string{root, upstream}
	// A real tree imports things calque does not vendor -- opentelemetry, in
	// the one this was first pointed at. CALQUE_REFERENCE_INCLUDE is where they
	// come from; buf's module cache already holds them.
	if extra := os.Getenv("CALQUE_REFERENCE_INCLUDE"); extra != "" {
		paths = append(paths, strings.Split(extra, ":")...)
	}

	req, err := protoc.CompileRequest(t.Context(), paths, "", files...)
	require.NoError(t, err, "the reference protos must compile")

	s, reg, err := ormcompat.ParseFiles(req)
	require.NoError(t, err)

	cfg, err := gen.ParseConfig([]byte(`
version: 1
targets:
  - {target: ts, backend: dexie}
ts:
  runtime: "@protobuf-orm/runtime"
  header: "// Code generated by protoc-gen-orm-ts. DO NOT EDIT."
`), "calque.yaml")
	require.NoError(t, err)

	r := gen.NewRegistry().Target(ts.New()).Backend(dexie.New())
	out, err := gen.Run(s, cfg, r, gen.WithDescriptors(req, reg), gen.WithWarnings(os.Stderr))
	require.NoError(t, err)

	t.Logf("calque emitted %d files", out.Len())

	var missing, differ, same int
	for _, name := range out.Names() {
		body, _ := out.Body(name)
		ref := filepath.Join(want, name)
		w, err := os.ReadFile(ref)
		if err != nil {
			missing++
			t.Errorf("no committed counterpart for %s", name)
			continue
		}
		if string(w) == string(body) {
			same++
			continue
		}
		differ++
		if differ <= 2 {
			t.Errorf("%s differs:\n--- committed\n%s\n--- calque\n%s", name, firstDiff(string(w), string(body)), "")
		}
	}
	t.Logf("identical=%d differ=%d missing=%d", same, differ, missing)
}

func firstDiff(a, b string) string {
	la, lb := strings.Split(a, "\n"), strings.Split(b, "\n")
	for i := 0; i < len(la) && i < len(lb); i++ {
		if la[i] != lb[i] {
			return "line " + itoa(i+1) + "\n  committed: " + quote(la[i]) + "\n  calque:    " + quote(lb[i])
		}
	}
	if len(la) != len(lb) {
		return "line count " + itoa(len(la)) + " vs " + itoa(len(lb))
	}
	return "(no line differs)"
}

func itoa(n int) string {
	if n == 0 {
		return "0"
	}
	var b []byte
	for n > 0 {
		b = append([]byte{byte('0' + n%10)}, b...)
		n /= 10
	}
	return string(b)
}

func quote(s string) string { return "\"" + strings.ReplaceAll(s, "\t", "\\t") + "\"" }
