// Package ts emits TypeScript for the Dexie backend.
//
// Its first job is to be a drop-in for protoc-gen-orm-ts: byte-identical output
// apart from the header and the runtime import specifier, so that swapping
// generators in an existing repository produces a diff a person can read. Every
// oddity reproduced here — a trailing space, a missing semicolon, an index
// spelled with the wrong name — is reproduced because the diff is the review,
// and a change mixed into it cannot be told from a mistake.
//
// The bugs are fixed afterwards, one commit each, where the diff for each is
// exactly the change it claims to be.
package ts

import (
	"fmt"
	"strings"

	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/reflect/protoregistry"

	"github.com/heojeongbo/calque/backend/dexie"
	"github.com/heojeongbo/calque/gen"
	"github.com/heojeongbo/calque/internal/tsw"
	"github.com/heojeongbo/calque/schema"
)

// Options is the `ts:` config section.
type Options struct {
	// Runtime is the module generated code imports. The predecessor hardcoded
	// "@protobuf-orm/runtime"; calque's is configurable so the emitted
	// specifier is a setting rather than a constant nobody can move.
	Runtime string `yaml:"runtime"`

	// Header is the first line of every generated file.
	Header string `yaml:"header"`

	// ImportExtension is appended to a relative import. The predecessor emitted
	// ".ts" and the consuming repository stripped it again with a regex over
	// every generated file; emitting what is wanted removes the post-pass.
	ImportExtension string `yaml:"import_extension"`
}

func (o *Options) setDefaults() {
	if o.Runtime == "" {
		o.Runtime = "@heojeongbo/calque-dexie"
	}
	if o.Header == "" {
		o.Header = "// Code generated by calque. DO NOT EDIT."
	}
}

// Target emits TypeScript.
type Target struct {
	opts Options
}

// New returns the target.
func New() *Target { return &Target{} }

func (t *Target) Name() string { return "ts" }

// Backends is the stores this target's runtime ships an adapter for.
func (t *Target) Backends() []string { return []string{"dexie"} }

func (t *Target) Configure(cfg *gen.Config, section string) error {
	var opts Options
	if err := gen.Claim(cfg, section, &opts, (*Options).setDefaults); err != nil {
		return err
	}
	t.opts = opts
	return nil
}

// pkg is one proto package's worth of output.
//
// Output is grouped by proto package because that is what the file layout is:
// one client.g.ts and at most one db.g.ts per package. The predecessor derived
// its output directory from whichever generate-marked file happened to be
// iterated last, which worked only because buf runs a local plugin once per
// directory by default.
type pkg struct {
	name     string
	dir      string
	entities []*entity
	services []protoreflect.ServiceDescriptor
}

// entity pairs an entity with the service that names it, which is how the
// predecessor decides whether to emit a table at all.
type entity struct {
	def     *schema.Entity
	service protoreflect.ServiceDescriptor
	ref     protoreflect.MessageDescriptor

	// keyProp is the property its Ref's key lives under -- see refOneof. It is
	// resolved once here rather than at each of the dozen places the emitted code
	// dereferences it, which is how it came to be the literal `key` at all of
	// them.
	keyProp string

	// targetKeyProp is the same, for an edge target: an index member spanning an
	// edge reads the *target* entity's Ref, which is a different message and may
	// spell its oneof differently.
	targetKeyProp func(*schema.Edge) string
}

// module is the entity's own _pb module, as a relative import.
func (e *entity) module() string {
	return pbModule(e.def.Source().ParentFile().Path())
}

// serviceModule is the module the service's request messages live in.
func (e *entity) serviceModule() string {
	if e.service == nil {
		return ""
	}
	return pbModule(e.service.ParentFile().Path())
}

// pbModule is protoc-gen-es's file naming: the proto path without its
// extension, plus "_pb", basename only because the import is a sibling.
func pbModule(path string) string {
	base := strings.TrimSuffix(path, ".proto")
	if i := strings.LastIndex(base, "/"); i >= 0 {
		base = base[i+1:]
	}
	return base + "_pb"
}

// lower is the file-name and property spelling the predecessor uses for an
// entity: the message name, lower-cased whole.
//
// Not camelCase. "PosePreset" becomes "posepreset", and the consuming
// application's DbClient depends on that spelling.
func lower(e *schema.Entity) string { return strings.ToLower(e.Name()) }

func (t *Target) Emit(g *gen.Generator) ([]gen.File, error) {
	pkgs, err := t.group(g)
	if err != nil {
		return nil, err
	}

	backend, ok := g.Backend().(*dexie.Backend)
	if !ok {
		return nil, fmt.Errorf("ts: backend %q is not dexie", g.Backend().Name())
	}

	var out []gen.File
	done, total := 0, len(pkgs)

	for _, p := range pkgs {
		client, err := t.emitClient(g, p)
		if err != nil {
			return nil, err
		}
		out = append(out, gen.File{Name: p.dir + "/client.g.ts", Body: client})

		// db.g.ts only exists when something is in it.
		if len(p.entities) > 0 {
			out = append(out, gen.File{Name: p.dir + "/db.g.ts", Body: t.emitDb(p)})
		}

		for _, e := range p.entities {
			body, err := t.emitEntity(g, backend, e)
			if err != nil {
				return nil, err
			}
			out = append(out, gen.File{Name: p.dir + "/" + lower(e.def) + ".db.g.ts", Body: body})
			t.warnMismatches(g, backend, e)
		}

		done++
		g.Step(done, total, p.name)
	}
	return out, nil
}

// warnMismatches says which indexes are declared under a name no row carries.
//
// The bytes stay identical; the report does not. This is what would have caught
// the two live instances of this five months before anyone went looking.
func (t *Target) warnMismatches(g *gen.Generator, b *dexie.Backend, e *entity) {
	for _, p := range b.Mismatches(e.def) {
		g.Warnf("%s: index component %q is stored as %q; the index is declared under a name no row has, so it is never used\n"+
			"\tcompat: orm-ts is reproducing protoc-gen-orm-ts here. Set dexie.compat: none to fix it — that changes the stored schema and needs a Dexie version bump.",
			e.def.FullName(), p.Names().Proto, p.Names().Value)
	}
}

// group buckets the entities to emit by proto package, and finds each one's
// service and Ref message.
func (t *Target) group(g *gen.Generator) ([]*pkg, error) {
	byName := map[string]*pkg{}
	var order []string

	add := func(name string) *pkg {
		p, ok := byName[name]
		if !ok {
			p = &pkg{name: name, dir: strings.ReplaceAll(name, ".", "/")}
			byName[name] = p
			order = append(order, name)
		}
		return p
	}

	// Every generate-marked file contributes its package, so a package with
	// services and no entities still gets its client.g.ts — the predecessor
	// emits those, and an absent file is a diff.
	//
	// The walk is over ProtoFile rather than FileToGenerate, because that is
	// the order protoc sends: dependency-first, which is what decides the order
	// services appear in. ormcompat walks the same list for the same reason,
	// so entities and services agree.
	if files := g.Files(); files != nil {
		generate := map[string]bool{}
		for _, name := range g.Request().GetFileToGenerate() {
			generate[name] = true
		}
		for _, fdp := range g.Request().GetProtoFile() {
			if !generate[fdp.GetName()] {
				continue
			}
			fd, err := files.FindFileByPath(fdp.GetName())
			if err != nil {
				return nil, fmt.Errorf("ts: %s: %w", fdp.GetName(), err)
			}
			p := add(string(fd.Package()))

			svcs := fd.Services()
			for i := range svcs.Len() {
				p.services = append(p.services, svcs.Get(i))
			}
		}
	}

	for _, e := range g.Sources() {
		p := add(e.Package())

		svc, ref := t.lookup(g, e)
		if svc == nil {
			// No service means no table: that is how the predecessor decides,
			// and an entity without one is modelled but not stored.
			continue
		}
		// A Ref whose oneof cannot be picked out sends every case label to
		// defaultLabel, which computes what this would otherwise read. Say so
		// once per entity rather than emitting the computed spelling in silence.
		if ref != nil && soleOneof(ref) == nil {
			g.Warnf("%s: %sRef has %d oneofs, so the lookup case labels cannot be read off it and are computed instead\n"+
				"  a Ref message needs exactly one oneof; its name does not matter",
				e.FullName(), e.Name(), ref.Oneofs().Len())
		}
		p.entities = append(p.entities, &entity{
			def:     e,
			service: svc,
			ref:     ref,
			keyProp: refOneof(g.Files(), e.FullName()),
			targetKeyProp: func(edge *schema.Edge) string {
				return refOneof(g.Files(), edge.Target().FullName())
			},
		})
	}

	out := make([]*pkg, 0, len(order))
	for _, name := range order {
		out = append(out, byName[name])
	}
	return out, nil
}

// lookup finds <Entity>Service and <Entity>Ref in the entity's package.
func (t *Target) lookup(g *gen.Generator, e *schema.Entity) (protoreflect.ServiceDescriptor, protoreflect.MessageDescriptor) {
	files := g.Files()
	if files == nil {
		return nil, nil
	}

	var svc protoreflect.ServiceDescriptor
	if d, err := files.FindDescriptorByName(protoreflect.FullName(e.FullName() + "Service")); err == nil {
		svc, _ = d.(protoreflect.ServiceDescriptor)
	}
	var ref protoreflect.MessageDescriptor
	if d, err := files.FindDescriptorByName(protoreflect.FullName(e.FullName() + "Ref")); err == nil {
		ref, _ = d.(protoreflect.MessageDescriptor)
	}
	return svc, ref
}

// caseLabel is the Ref oneof case a candidate key is reached through.
//
// It is read off the Ref message by field number rather than computed from the
// key's name. Computing it is what the predecessor does, and it is why the
// store and the query can disagree about how a prop is spelled: two functions,
// two answers, nothing comparing them. Reading the descriptor means there is
// one answer, and it is the one the request message actually carries.
//
// The oneof is found by being the only one, not by being called `key`. Asking
// for that name is what this did, and a schema spelling the oneof anything else
// got nothing back -- so every label fell through to defaultLabel, which for an
// index reproduces strcase.ToCamel instead of reading protoc's JSON name. Those
// two agree for an ordinary snake_case name and are not guaranteed to, which is
// the kind of dependency worth not having. The Go target read the same message
// with no such requirement: two targets, two rules for one message.
//
// Nothing needs the name. One oneof is unambiguous whatever it is called, and two
// are a schema neither target can read.
func caseLabel(ref protoreflect.MessageDescriptor, key schema.Elem) (string, bool) {
	if ref == nil {
		return "", false
	}
	oneof := soleOneof(ref)
	if oneof == nil {
		return "", false
	}
	for i := range oneof.Fields().Len() {
		f := oneof.Fields().Get(i)
		if int32(f.Number()) == key.Number() {
			return f.JSONName(), true
		}
	}
	return "", false
}

// refOneof is the property a <Entity>Ref's key lives under.
//
// The emitted code reads and writes it -- `req.ref?.key`, `{key:{case:…}}` -- so
// this has to be what protobuf-es actually generated, which is the oneof's own
// name lower-camelled. It used to be the literal `key` in a dozen places, which
// is correct for every schema that calls it that and silently wrong for one that
// does not: the Go target emits `WhichLookup()` from the descriptor and would
// disagree with a TypeScript file still saying `.key`.
//
// `key` remains the answer when there is nothing to read -- an entity with no Ref
// message emits nothing that dereferences it, and a Ref with several oneofs has
// already been warned about.
func refOneof(files *protoregistry.Files, entity string) string {
	const fallback = "key"
	if files == nil {
		return fallback
	}
	d, err := files.FindDescriptorByName(protoreflect.FullName(entity + "Ref"))
	if err != nil {
		return fallback
	}
	md, ok := d.(protoreflect.MessageDescriptor)
	if !ok {
		return fallback
	}
	o := soleOneof(md)
	if o == nil {
		return fallback
	}
	return toCamel(string(o.Name()))
}

// soleOneof is a message's only oneof, or nil if it has none or several.
//
// Several is not a case to pick a winner in. Which one holds the lookups would
// be a guess, and a guess here produces output that compiles and queries the
// wrong field, so it is reported rather than resolved -- by the caller, which
// knows what it was looking for.
func soleOneof(md protoreflect.MessageDescriptor) protoreflect.OneofDescriptor {
	os := md.Oneofs()
	if os.Len() != 1 {
		return nil
	}
	return os.Get(0)
}

// orderedServices is the services in the order they were collected, which is
// request order: dependency-first, as protoc sends it.
//
// Sorting them would be tidier and wrong. The order in the committed output is
// Audit, Auth, Tenant, Btree, ... which is neither alphabetical nor by path --
// it is the order the files arrive in, and matching it is the difference
// between a clean diff and a reordered one.
func orderedServices(p *pkg) []protoreflect.ServiceDescriptor { return p.services }

// emitDb writes db.g.ts: the intersection type, the client interface, the
// service map, and the schema map the application feeds to Dexie.
func (t *Target) emitDb(p *pkg) []byte {
	f := tsw.New()
	gen.Preamble(f, t.opts.Header, "")
	f.P()

	for _, e := range p.entities {
		f.P(`import * as `, e.def.Name(), ` from "./`, lower(e.def), `.db.g`, t.opts.ImportExtension, `";`)
	}
	f.P()

	// The trailing space is not a typo. It is in the committed output, and the
	// diff that proves this is a drop-in is byte-for-byte.
	f.P(`export type Db = `)
	for _, e := range p.entities {
		f.P("\t& ", e.def.Name(), ".Db")
	}
	f.P()

	f.P(`export interface DbClient {`)
	for _, e := range p.entities {
		f.P("\treadonly ", lower(e.def), ": ", e.def.Name(), ".TableService")
	}
	f.P(`}`)
	f.P()

	f.P(`export const DbService = {`)
	for _, e := range p.entities {
		f.P("\t[", e.def.Name(), ".TableName]: ", e.def.Name(), ".TableService,")
	}
	f.P(`}`)
	f.P()

	f.P(`export function schemas(){`)
	f.P("\treturn {")
	for _, e := range p.entities {
		f.P("\t\t[", e.def.Name(), ".TableName]: ", e.def.Name(), ".Schema,")
	}
	f.P("\t} as const")
	f.P(`}`)

	return f.Bytes()
}
