// Package service emits the `.proto` service contract calque's other targets
// read.
//
// It is the odd one out twice over. It produces `.proto` rather than a language,
// so its output is another generator's input and a build runs in two passes; and
// it describes what may be asked for rather than where anything is kept, so it
// declares gen.Storeless and is paired with no backend.
//
// The contract per entity is six messages and a service:
//
//	service <E>Service { Add Get Patch Erase }
//	<E>AddRequest  <E>RefBy<Index>  <E>Ref  <E>Select  <E>GetRequest  <E>PatchRequest
//
// and nothing else. List, Watch and Scrape are not in the annotation vocabulary --
// orm.RpcOptions knows `crud` and the four operations above -- so a contract that
// has them was extended by hand, and this target must leave room for that rather
// than own the whole file. See docs/targets/service.md.
package service

import (
	"path"
	"strings"

	"google.golang.org/protobuf/reflect/protoreflect"

	"github.com/heojeongbo/calque/gen"
	"github.com/heojeongbo/calque/internal/prow"
	"github.com/heojeongbo/calque/schema"
)

// Options is the `service:` config section.
type Options struct {
	// Header is the first line of every generated file.
	//
	// It is settable for the same reason the other targets' is: proving this is a
	// drop-in means generating what the previous generator generated, and its
	// first line named itself.
	Header string `yaml:"header"`

	// Suffix is appended to the source file's base name, extension included.
	Suffix string `yaml:"suffix"`
}

func (o *Options) setDefaults() {
	if o.Header == "" {
		o.Header = "// Code generated by calque. DO NOT EDIT."
	}
	if o.Suffix == "" {
		o.Suffix = "_svc.g.proto"
	}
}

// Target emits service contracts.
type Target struct {
	opts Options
}

// New returns the target.
func New() *Target { return &Target{} }

func (t *Target) Name() string { return "service" }

// Backends is nil because Storeless means the question never gets asked.
func (t *Target) Backends() []string { return nil }

// Storeless declares that this target emits nothing store-specific. See
// gen.Storeless.
func (t *Target) Storeless() {}

func (t *Target) Configure(cfg *gen.Config, section string) error {
	var opts Options
	if err := gen.Claim(cfg, section, &opts, (*Options).setDefaults); err != nil {
		return err
	}
	t.opts = opts
	return nil
}

// entity is one entity plus the descriptor facts writing its contract needs.
type entity struct {
	def *schema.Entity

	// pkg is the proto package the contract is emitted into, which is the
	// source's. A type declared there is written without it.
	pkg protoreflect.FullName
}

// file is one output file: every entity declared in one source file.
//
// Output is per source file rather than per entity, so two entities in one proto
// produce one contract carrying both -- which is why the convention is one entity
// per file (docs/conventions.md).
type file struct {
	source   string
	pkg      protoreflect.FullName
	goPkg    string
	entities []*entity
}

func (t *Target) Emit(g *gen.Generator) ([]gen.File, error) {
	files, err := t.group(g)
	if err != nil {
		return nil, err
	}

	out := make([]gen.File, 0, len(files))
	for i, f := range files {
		if f.goPkg == "" {
			g.Warnf("%s: no `option go_package` on the source, so %s carries none either; protoc-gen-go will refuse it",
				f.source, t.outName(f.source))
		}
		body, err := t.emitFile(f)
		if err != nil {
			return nil, err
		}
		out = append(out, gen.File{Name: t.outName(f.source), Body: body})
		g.Step(i+1, len(files), path.Base(f.source))
	}
	return out, nil
}

// outName is the source path with its base name suffixed, so apptest.proto
// becomes apptest_svc.g.proto beside it.
func (t *Target) outName(source string) string {
	dir, base := path.Split(source)
	return dir + strings.TrimSuffix(base, path.Ext(base)) + t.opts.Suffix
}

// group buckets the entities to emit by the file that declared them.
//
// In Sources() order, which is request order -- dependency-first -- so the output
// file set and the order inside each file do not depend on a map.
func (t *Target) group(g *gen.Generator) ([]*file, error) {
	byPath := map[string]*file{}
	var order []string

	for _, e := range g.Sources() {
		src := e.Source().ParentFile()
		p := src.Path()

		f, ok := byPath[p]
		if !ok {
			f = &file{source: p, pkg: src.Package(), goPkg: goPackage(src)}
			byPath[p] = f
			order = append(order, p)
		}
		f.entities = append(f.entities, &entity{def: e, pkg: f.pkg})
	}

	out := make([]*file, 0, len(order))
	for _, p := range order {
		out = append(out, byPath[p])
	}
	return out, nil
}

// goPackage is the source file's go_package, carried through to the contract so
// that the request messages compile into the same Go package as the entity's.
//
// A source without one is not an error. A proto tree generated only for TypeScript
// has no reason to carry a Go import path, and refusing here would impose
// protogen's cost on a target that does not need it -- see
// docs/architecture.md. The line is omitted instead, and the omission is reported,
// because a Go consumer of the result will refuse it for a reason that does not
// mention this target.
//
// Read off the descriptor rather than through protogen, which matters in a buf
// build: managed mode rewrites this option before a plugin sees it, so the
// descriptor already carries the value the rest of the pipeline will use.
func goPackage(fd protoreflect.FileDescriptor) string {
	opts, _ := fd.Options().(interface{ GetGoPackage() string })
	if opts == nil {
		return ""
	}
	return opts.GetGoPackage()
}

// emitFile writes one contract.
//
// Declaration order is the whole file's contract with the merge tool that folds
// hand-written extensions into it, so it is fixed: per entity, the service first
// and then its messages, in the order the generator being replaced completed them
// -- which is post-order, so a RefBy wrapper precedes the Ref that names it.
func (t *Target) emitFile(f *file) ([]byte, error) {
	imports := newImports()
	imports.add(f.source)

	// An entity whose edge target lives in the same source file would otherwise
	// have this file import itself, which protoc refuses.
	self := t.outName(f.source)

	// The body is rendered first so that the imports it needs are known before
	// the preamble that lists them is written.
	body := prow.New()
	for i, e := range f.entities {
		if i > 0 {
			body.P()
		}
		if err := t.emitEntity(body, e, imports, t.outName, self); err != nil {
			return nil, err
		}
	}

	head := prow.New()
	gen.Preamble(head, t.opts.Header, f.source)
	head.P()
	head.P(`edition = "2023";`)
	head.P()
	head.P("package ", f.pkg, ";")
	head.P()
	for _, p := range imports.sorted() {
		head.P("import ", prow.Quote(p), ";")
	}
	if len(imports.sorted()) > 0 {
		head.P()
	}
	if f.goPkg != "" {
		head.P("option go_package = ", prow.Quote(f.goPkg), ";")
		head.P()
	}

	return append(head.Bytes(), body.Bytes()...), nil
}

// emitEntity writes one entity's service and messages.
//
// Which messages exist depends on which operations the entity declared: Ref is
// needed by get, patch and erase; Select only by get; and the two request bodies
// by the operation named after them. An entity that declares nothing still gets an
// empty service, which is what the generator being replaced emits and what the
// TypeScript target looks for to decide there is a table at all.
func (t *Target) emitEntity(f *prow.File, e *entity, imports *imports, outName func(string) string, self string) error {
	rpc := e.def.Rpc()
	out := func(target *schema.Entity) string {
		if p := outName(target.Source().ParentFile().Path()); p != self {
			return p
		}
		return ""
	}

	needsRef := rpc.Has(schema.OpGet) || rpc.Has(schema.OpPatch) || rpc.Has(schema.OpErase)

	if rpc.Has(schema.OpErase) {
		imports.add("google/protobuf/empty.proto")
	}

	t.emitService(f, e, func() string { return "google.protobuf.Empty" })

	if rpc.Has(schema.OpAdd) {
		f.P()
		for _, p := range e.def.Props() {
			if fld, ok := p.(*schema.Field); ok && fld.IsVersion() {
				continue
			}
			imports.need(p, out)
		}
		t.emitAdd(f, e)
	}

	if needsRef {
		// The wrappers come first because the Ref names them, and a reader
		// meeting a type before its declaration is a diff against the file this
		// replaces rather than a preference.
		for _, idx := range e.def.Indexes() {
			if !idx.IsUnique() || idx.IsHidden() {
				continue
			}
			f.P()
			for _, p := range idx.Props() {
				imports.need(p, out)
			}
			t.emitRefBy(f, e, idx)
		}
		f.P()
		if err := t.emitRef(f, e); err != nil {
			return err
		}
	}

	if rpc.Has(schema.OpGet) {
		f.P()
		for _, p := range e.def.Props() {
			if edge, ok := p.(*schema.Edge); ok {
				imports.add(out(edge.Target()))
			}
		}
		t.emitSelect(f, e)
		f.P()
		t.emitGet(f, e)
	}

	if rpc.Has(schema.OpPatch) {
		f.P()
		for _, p := range e.def.Props() {
			if p.IsImmutable() {
				continue
			}
			imports.need(p, out)
		}
		if err := t.emitPatch(f, e); err != nil {
			return err
		}
	}
	return nil
}
