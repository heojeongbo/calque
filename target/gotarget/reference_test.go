package gotarget_test

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/stretchr/testify/require"

	"github.com/HeoJeongBo/calque/backend/entsql"
	"github.com/HeoJeongBo/calque/gen"
	"github.com/HeoJeongBo/calque/internal/protoc"
	"github.com/HeoJeongBo/calque/ormcompat"
	gotarget "github.com/HeoJeongBo/calque/target/gotarget"
)

// TestReferenceSchemas generates ent schema types from a real proto tree and
// compares them against what protoc-gen-orm-ent committed.
//
// Byte equality is not the bar here -- ent reads these, and what matters is the
// physical schema they produce. But a diff that is only whitespace is worth
// knowing about too, so this reports both.
func TestReferenceSchemas(t *testing.T) {
	root := os.Getenv("CALQUE_REFERENCE_PROTO")
	want := os.Getenv("CALQUE_REFERENCE_GO")
	if root == "" || want == "" {
		t.Skip("set CALQUE_REFERENCE_PROTO and CALQUE_REFERENCE_GO")
	}

	var files []string
	require.NoError(t, filepath.Walk(root, func(p string, info os.FileInfo, err error) error {
		if err != nil || info.IsDir() || !strings.HasSuffix(p, ".proto") {
			return err
		}
		rel, _ := filepath.Rel(root, p)
		files = append(files, filepath.ToSlash(rel))
		return nil
	}))
	require.NotEmpty(t, files)

	upstream, _ := filepath.Abs("../../testdata/proto/_upstream")
	paths := []string{root, upstream}
	if extra := os.Getenv("CALQUE_REFERENCE_INCLUDE"); extra != "" {
		paths = append(paths, strings.Split(extra, ":")...)
	}

	param := os.Getenv("CALQUE_REFERENCE_PARAM")
	req, err := protoc.CompileRequest(t.Context(), paths, param, files...)
	require.NoError(t, err, "the reference protos must compile")

	s, reg, err := ormcompat.ParseFiles(req)
	require.NoError(t, err)

	cfg, err := gen.ParseConfig([]byte(`
version: 1
targets:
  - {target: go, backend: entsql}
go:
  header: "// Code generated by protoc-gen-orm-ent. DO NOT EDIT."
`), "calque.yaml")
	require.NoError(t, err)

	r := gen.NewRegistry().Target(gotarget.New()).Backend(entsql.New())
	out, err := gen.Run(s, cfg, r, gen.WithDescriptors(req, reg), gen.WithWarnings(os.Stderr))
	require.NoError(t, err)

	t.Logf("calque emitted %d files", out.Len())

	var same, differ, missing int
	for _, name := range out.Names() {
		body, _ := out.Body(name)
		w, err := os.ReadFile(filepath.Join(want, name))
		if err != nil {
			missing++
			t.Errorf("no committed counterpart for %s", name)
			continue
		}
		if string(w) == string(body) {
			same++
			continue
		}
		differ++
		if differ <= 1 {
			t.Errorf("%s differs:\n%s", name, firstDiff(string(w), string(body)))
		}
	}
	t.Logf("identical=%d differ=%d missing=%d", same, differ, missing)
}

func firstDiff(a, b string) string {
	la, lb := strings.Split(a, "\n"), strings.Split(b, "\n")
	for i := 0; i < len(la) && i < len(lb); i++ {
		if la[i] != lb[i] {
			return "line " + itoa(i+1) + "\n  committed: " + q(la[i]) + "\n  calque:    " + q(lb[i])
		}
	}
	return "line count " + itoa(len(la)) + " vs " + itoa(len(lb))
}

func itoa(n int) string {
	if n == 0 {
		return "0"
	}
	var b []byte
	for n > 0 {
		b = append([]byte{byte('0' + n%10)}, b...)
		n /= 10
	}
	return string(b)
}

func q(s string) string { return "\"" + strings.ReplaceAll(s, "\t", "\\t") + "\"" }
