// Package gotarget emits Go for the ent/SQL backend.
//
// Unlike the TypeScript target it uses protogen, and the difference is not an
// inconsistency. ormcompat avoids protogen because protogen.Options.New fails
// on any file in the closure without a go_package, and a proto tree generated
// only for TypeScript has no reason to carry one. A Go target has every reason:
// it needs Go identifiers, Go import paths, and the api-level flags protoc-gen-go
// was given. So the cost of protogen is paid by the target that benefits from
// it, and by nobody else.
//
// What it emits first is the ent schema — and only that. Getting those 769
// lines right pins every column, index and foreign key in the physical
// database, because ent expands them into the rest. It is checkable on its own,
// before a line of server code exists, by running `ent generate` and diffing
// migrate/schema.go.
package gotarget

import (
	"fmt"
	"path"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/reflect/protoreflect"

	"github.com/HeoJeongBo/calque/backend/entsql"
	"github.com/HeoJeongBo/calque/gen"
	"github.com/HeoJeongBo/calque/schema"
)

// Options is the `go:` config section.
type Options struct {
	// SchemaDir is where the ent schema types go, relative to the Go package
	// the protos declare.
	SchemaDir string `yaml:"schema_dir"`

	// EntDir is the ent package the conversion helpers are written into. They
	// have to live there because they are methods on ent's own types.
	EntDir string `yaml:"ent_dir"`

	// BareDir is where the generated servers go, relative to the proto's Go
	// package.
	BareDir string `yaml:"bare_dir"`

	// Header is the first line of every generated file.
	Header string `yaml:"header"`

	// QueryHeader is the first line of query.g.go and store.g.go, which
	// defaults to Header.
	//
	// It exists because the two file groups came from two different upstream
	// generators -- the ent schema from protoc-gen-orm-ent and these from
	// protoc-gen-orm-go -- and a drop-in that changes line 1 of every file is
	// not a drop-in. Set only Header if you are not replacing anything.
	QueryHeader string `yaml:"query_header"`
}

func (o *Options) setDefaults() {
	if o.SchemaDir == "" {
		o.SchemaDir = "schema"
	}
	if o.EntDir == "" {
		o.EntDir = "ent"
	}
	if o.BareDir == "" {
		o.BareDir = "server/bare"
	}
	if o.Header == "" {
		o.Header = "// Code generated by calque. DO NOT EDIT."
	}
	if o.QueryHeader == "" {
		o.QueryHeader = o.Header
	}
}

// Target emits Go.
type Target struct {
	opts Options
}

func New() *Target { return &Target{} }

func (t *Target) Name() string { return "go" }

// Backends is ent-shaped stores only. A Go target over a document store would
// be a different target, not this one with a different backend: ent's API is
// per-entity generated types and nothing abstracts over them.
func (t *Target) Backends() []string { return []string{"entsql"} }

func (t *Target) Configure(cfg *gen.Config, section string) error {
	var opts Options
	if _, err := cfg.Section(section, &opts); err != nil {
		return err
	}
	opts.setDefaults()
	t.opts = opts
	return nil
}

func (t *Target) Emit(g *gen.Generator) ([]gen.File, error) {
	backend, ok := g.Backend().(*entsql.Backend)
	if !ok {
		return nil, fmt.Errorf("go: backend %q does not speak ent", g.Backend().Name())
	}
	if g.Request() == nil {
		return nil, fmt.Errorf("go: no descriptors; the target needs the plugin request")
	}

	// protogen parses module=, M<file>=, default_api_level= and friends out of
	// the same parameter string protoc-gen-go was given, so calque agrees with
	// it about Go names by construction rather than by imitation.
	pg, err := protogen.Options{}.New(g.Request())
	if err != nil {
		return nil, fmt.Errorf("go: %w", err)
	}

	e := &emitter{
		target:  t,
		gen:     g,
		backend: backend,
		pg:      pg,
		msgs:    map[protoreflect.FullName]*protogen.Message{},
		files:   map[string]*protogen.File{},
	}
	for _, f := range pg.Files {
		e.files[f.Desc.Path()] = f
		e.index(f.Messages)
	}

	return e.emitSchemas()
}

// emitter holds the descriptor lookups the emission needs.
type emitter struct {
	target  *Target
	gen     *gen.Generator
	backend *entsql.Backend
	pg      *protogen.Plugin

	msgs  map[protoreflect.FullName]*protogen.Message
	files map[string]*protogen.File
}

func (e *emitter) index(msgs []*protogen.Message) {
	for _, m := range msgs {
		e.msgs[m.Desc.FullName()] = m
		e.index(m.Messages)
	}
}

// message finds protogen's view of a message, which is where its Go identifier
// and import path live.
func (e *emitter) message(name protoreflect.FullName) (*protogen.Message, bool) {
	m, ok := e.msgs[name]
	return m, ok
}

// file finds protogen's view of the file an entity came from.
func (e *emitter) file(en *schema.Entity) (*protogen.File, bool) {
	f, ok := e.files[en.File()]
	return f, ok
}

// schemaPath is where an entity's ent schema type is written.
//
// It is the entity's own Go package, plus the schema directory, plus the proto
// file's basename -- pose_preset.proto becomes pose_preset.go even though the
// entity is PosePreset. protogen strips the module prefix when it builds the
// response.
func (e *emitter) schemaPath(en *schema.Entity) (string, error) {
	f, ok := e.file(en)
	if !ok {
		return "", fmt.Errorf("go: %s: no protogen file for %s", en.FullName(), en.File())
	}
	base := strings.TrimSuffix(path.Base(en.File()), ".proto")
	return path.Join(string(f.GoImportPath), e.target.opts.SchemaDir, base+".go"), nil
}
