// Package swifttarget emits Swift for the GRDB backend.
//
// It sits where the TypeScript target sits — a language bound to a local store,
// fed by a server that holds the record — and it is written against the same
// two rules that target learned the hard way:
//
//   - Names come from schema.Names, never from a descriptor and never from a
//     casing function invented here. A prop's Swift property name is its
//     ValueName, which protoc already decided; its column is the backend's
//     StorePath. Mixing the two is the bug the name types exist to prevent.
//   - The store's syntax belongs to the runtime adapter. This file decides what
//     a row looks like and what a value turns into; the GRDB calls are the
//     Swift package's.
//
// Unlike the TypeScript target this one has no predecessor to be byte-identical
// with, so it emits what reads well rather than what some other generator
// happened to emit.
package swifttarget

import (
	"fmt"
	"sort"
	"strings"

	"github.com/heojeongbo/calque/backend/grdb"
	"github.com/heojeongbo/calque/gen"
	"github.com/heojeongbo/calque/internal/swiftw"
	"github.com/heojeongbo/calque/schema"
)

// The visibilities a generated declaration can have.
const (
	// AccessInternal is the default: a public declaration in an app target is a
	// warning nobody can act on.
	AccessInternal = "internal"
	// AccessPublic is for generated code that ships as its own module.
	AccessPublic = "public"
)

// Options is the `swift:` config section.
type Options struct {
	// Runtime is the module generated code imports for the codecs and the
	// store protocol. Configurable rather than constant so the package can move
	// without a generator release.
	Runtime string `yaml:"runtime"`

	// Header is the first line of every generated file.
	Header string `yaml:"header"`

	// AccessLevel is the visibility of generated declarations: "public" when
	// the generated code ships as its own module, "internal" when it is
	// compiled straight into the app target.
	//
	// It defaults to internal because that is what an app does, and a public
	// declaration in an app target is a warning nobody can act on.
	AccessLevel string `yaml:"access_level"`
}

func (o *Options) setDefaults() {
	if o.Runtime == "" {
		o.Runtime = "CalqueGRDB"
	}
	if o.Header == "" {
		o.Header = "// Code generated by calque. DO NOT EDIT."
	}
	if o.AccessLevel == "" {
		o.AccessLevel = AccessInternal
	}
}

// Target emits Swift.
type Target struct {
	opts Options
}

// New returns the target.
func New() *Target { return &Target{} }

func (t *Target) Name() string { return "swift" }

// Backends is grdb alone. There is one Swift runtime adapter and it speaks
// GRDB; naming any other store would emit a package importing an adapter
// nobody wrote.
func (t *Target) Backends() []string { return []string{"grdb"} }

func (t *Target) Configure(cfg *gen.Config, section string) error {
	var o Options
	if err := gen.Claim(cfg, section, &o, (*Options).setDefaults); err != nil {
		return err
	}
	acc, err := gen.OneOf("swift", "access_level", o.AccessLevel, AccessInternal, AccessInternal, AccessPublic)
	if err != nil {
		return err
	}
	o.AccessLevel = acc
	t.opts = o
	return nil
}

func (t *Target) Emit(g *gen.Generator) ([]gen.File, error) {
	backend, ok := g.Backend().(*grdb.Backend)
	if !ok {
		return nil, fmt.Errorf("swift: backend %q is not grdb", g.Backend().Name())
	}

	sources := g.Sources()
	out := make([]gen.File, 0, len(sources))
	for i, e := range sources {
		body, err := t.emitEntity(g, backend, e)
		if err != nil {
			return nil, err
		}
		out = append(out, gen.File{Name: string(e.Name()) + ".g.swift", Body: body})
		g.Step(i+1, len(sources), string(e.Name()))
	}
	return out, nil
}

// emitEntity writes one entity: the record struct, its columns, and its table.
func (t *Target) emitEntity(g *gen.Generator, b *grdb.Backend, e *schema.Entity) ([]byte, error) {
	table, err := g.Table(e)
	if err != nil {
		return nil, fmt.Errorf("swift: %s: %w", e.FullName(), err)
	}

	f := swiftw.New()
	gen.Preamble(f, t.opts.Header, string(e.FullName()))
	f.P()
	f.P("import Foundation")
	f.P("import GRDB")
	f.P("import ", t.opts.Runtime)
	f.P()

	name := string(e.Name())
	acc := t.opts.AccessLevel

	f.P(acc, " struct ", name, ": Codable, Equatable, Identifiable, Sendable {")
	f.In()

	props := e.Props()
	for _, p := range props {
		ty, err := t.swiftType(p)
		if err != nil {
			return nil, fmt.Errorf("swift: %s.%s: %w", e.FullName(), p.Name(), err)
		}
		// An immutable prop is `let`: the store cannot change it after insert,
		// so a `var` would offer a write the patch surface refuses.
		decl := "var"
		if p.IsImmutable() {
			decl = "let"
		}
		f.P(acc, " ", decl, " ", t.propName(p), ": ", ty)
	}

	// `id` satisfies Identifiable. The key is not always spelled `id`, so it is
	// aliased rather than assumed.
	key := e.Key()
	if key != nil && string(key.Names().Value) != "id" {
		ty, err := t.swiftType(key)
		if err != nil {
			return nil, err
		}
		f.P()
		f.P(acc, " var id: ", ty, " { ", t.propName(key), " }")
	}

	f.Out()
	f.P("}")
	f.P()

	// Columns, so a query names a column through the compiler rather than
	// through a string literal.
	f.P("extension ", name, " {")
	f.In()
	f.P(acc, " enum Columns: String, ColumnExpression {")
	f.In()
	for _, p := range props {
		col, err := b.Column(p)
		if err != nil {
			return nil, err
		}
		f.P("case ", t.propName(p), " = ", swiftw.Str(col))
	}
	f.Out()
	f.P("}")
	f.Out()
	f.P("}")
	f.P()

	// The table comes from the backend and not from Table.Extra, which is an
	// any-valued map: a renamed key there would print %!q(<nil>) into a Swift
	// file and nothing would fail. This target has already asserted its backend
	// is grdb, so it can ask a question with a type on it.
	f.P("extension ", name, ": FetchableRecord, PersistableRecord {")
	f.In()
	f.P(acc, " static let databaseTableName = ", swiftw.Str(grdb.TableName(e)))
	f.Out()
	f.P("}")

	// The codecs the runtime has to apply, named per column so the adapter and
	// the schema cannot drift apart silently.
	if codecs := t.codecLines(b, e, table); len(codecs) > 0 {
		f.P()
		f.P("extension ", name, " {")
		f.In()
		f.P("/// Column codecs, as the backend decided them.")
		f.P(acc, " static let calqueCodecs: [String: CalqueCodec] = [")
		f.In()
		for _, line := range codecs {
			f.P(line)
		}
		f.Out()
		f.P("]")
		f.Out()
		f.P("}")
	}

	return f.Bytes(), nil
}

// codecLines renders the codec table in a stable order, skipping identity —
// naming the transform that is no transform would be noise in every entity.
func (t *Target) codecLines(b *grdb.Backend, e *schema.Entity, table *gen.Table) []string {
	var lines []string
	for _, p := range e.Props() {
		codec := table.Codec[p]
		if codec == gen.CodecIdentity {
			continue
		}
		col, err := b.Column(p)
		if err != nil {
			continue
		}
		lines = append(lines, fmt.Sprintf("%s: .%s,", swiftw.Str(col), codecCase(codec)))
	}
	sort.Strings(lines)
	return lines
}

// codecCase turns "time-epoch-millis" into "timeEpochMillis".
func codecCase(c gen.CodecName) string {
	parts := strings.Split(string(c), "-")
	for i := 1; i < len(parts); i++ {
		if parts[i] == "" {
			continue
		}
		parts[i] = strings.ToUpper(parts[i][:1]) + parts[i][1:]
	}
	return strings.Join(parts, "")
}

// propName is the property's name on a decoded value.
//
// It is the ValueName -- protoc's JSON name -- and never a casing of the proto
// name computed here. Swift's convention and protobuf's JSON convention are both
// lowerCamelCase, so they agree; computing it anyway is how the two spellings
// got out of step in the generator this one learned from.
func (t *Target) propName(p schema.Prop) string {
	n := string(p.Names().Value)
	if reserved[n] {
		return "`" + n + "`"
	}
	return n
}

// swiftType is the Swift type a prop decodes into.
func (t *Target) swiftType(p schema.Prop) (string, error) {
	base, err := t.baseType(p)
	if err != nil {
		return "", err
	}
	if p.IsNullable() {
		return base + "?", nil
	}
	return base, nil
}

func (t *Target) baseType(p schema.Prop) (string, error) {
	// An edge is stored as its target's key, so it types as that key.
	if e, ok := p.(*schema.Edge); ok {
		if e.Target() == nil || e.Target().Key() == nil {
			return "", fmt.Errorf("edge points at an entity with no key")
		}
		return t.baseType(e.Target().Key())
	}

	switch p.Type() {
	case schema.TypeUUID:
		return "UUID", nil
	case schema.TypeTime:
		return "Date", nil
	case schema.TypeString:
		return "String", nil
	case schema.TypeBytes:
		return "Data", nil
	case schema.TypeBool:
		return "Bool", nil
	case schema.TypeInt32:
		return "Int32", nil
	case schema.TypeInt64:
		return "Int64", nil
	case schema.TypeUint32:
		return "UInt32", nil
	case schema.TypeUint64:
		return "UInt64", nil
	case schema.TypeFloat:
		return "Float", nil
	case schema.TypeDouble:
		return "Double", nil
	case schema.TypeJSON:
		return "Data", nil
	default:
		return "", fmt.Errorf("no Swift type for %s", p.Type())
	}
}

// reserved is the Swift keywords a property name can collide with. A collision
// is escaped with backticks rather than renamed: renaming would make the Swift
// property and the JSON name disagree, which is the one thing this target does
// not do.
var reserved = map[string]bool{
	"associatedtype": true, "class": true, "deinit": true, "enum": true,
	"extension": true, "fileprivate": true, "func": true, "import": true,
	"init": true, "inout": true, "internal": true, "let": true, "open": true,
	"operator": true, "private": true, "protocol": true, "public": true,
	"rethrows": true, "static": true, "struct": true, "subscript": true,
	"typealias": true, "var": true, "break": true, "case": true,
	"continue": true, "default": true, "defer": true, "do": true, "else": true,
	"fallthrough": true, "for": true, "guard": true, "if": true, "in": true,
	"repeat": true, "return": true, "switch": true, "where": true,
	"while": true, "as": true, "catch": true, "false": true, "is": true,
	"nil": true, "super": true, "self": true, "throw": true, "throws": true,
	"true": true, "try": true, "Type": true, "Protocol": true,
}
